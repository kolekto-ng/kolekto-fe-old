/**
 * bundle-edge.mjs — inline the engine into the self-contained Deno edge functions.
 *
 * The Supabase Edge Functions are deployed by pasting a single self-contained
 * file into the Supabase console — they cannot import a shared package or a
 * sibling directory. To give them the ONE canonical engine without hand-copied
 * duplication, this script flattens the engine source (kolekto-shared-financial/
 * src) into a single isolated IIFE — `const FPE = (() => { … })();` — and injects
 * it between marker comments in each target edge file. The engine is thus
 * inlined as a GENERATED artifact; the canonical source stays in src/, and the
 * golden-vector + differential suites prove the inlined copy is equivalent.
 *
 * The IIFE isolates the engine's scope, so the edge module keeps its own helpers
 * (asNumber, getInfoRows, …) with no name collisions. After the block, each edge
 * file binds its local names to `FPE.*` (e.g. `const calculateFees =
 * FPE.calculateFees`) so existing call sites are untouched.
 *
 * Usage:
 *   npm run bundle:edge
 * Idempotent: only the text between the markers is rewritten.
 */

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");
const SRC = join(pkgRoot, "src");

// Engine files in dependency order (types → constants → primitives → projections).
const ORDER = ["types.ts", "constants.ts", "primitives.ts", "projections.ts"];

// The public runtime API exposed from the IIFE (mirrors src/index.ts value exports).
const PUBLIC = [
  "roundCurrency", "platformFeeRate", "calculateFees", "deriveNetContribution",
  "normalizeContribution", "normalizeContributions", "getSettlementCutoff",
  "isPaymentSettled", "allocateAmounts", "computeWallet", "computeWalletBalances",
  "computeAvailableBalance", "computePendingBalance", "computeLedgerBalance",
  "computeOrganizerBalance", "computeCollectionTotals", "computePendingWithdrawals",
  "computeWithdrawalEligibility", "buildTierAvailability",
  "PLATFORM_FEE_RATES", "PLATFORM_FEE_RATE_DEFAULT", "GATEWAY_FEE_RATE",
  "MAX_FEE_AMOUNT", "SETTLEMENT_HOUR_UTC", "ONE_DAY_MS",
  "COMPLETED_WITHDRAWAL_STATUSES", "PENDING_WITHDRAWAL_STATUSES",
  "COLLECTION_TYPES", "FEE_BEARERS", "CONSTANTS",
];

const BEGIN = "// >>> FPE-ENGINE-INLINE (generated by kolekto-shared-financial/scripts/bundle-edge.mjs — DO NOT EDIT) >>>";
const END = "// <<< FPE-ENGINE-INLINE <<<";

/** Remove relative imports (single or multi-line) and leading `export ` keywords. */
function stripFile(text) {
  const out = [];
  let inImport = false;
  for (const line of text.split(/\r?\n/)) {
    if (inImport) {
      if (line.includes(";")) inImport = false;
      continue;
    }
    if (line.trimStart().startsWith("import ")) {
      if (!line.includes(";")) inImport = true;
      continue;
    }
    out.push(line.replace(/^(\s*)export\s+/, "$1"));
  }
  return out.join("\n");
}

function indent(text, pad = "  ") {
  return text
    .split("\n")
    .map((l) => (l.length ? pad + l : l))
    .join("\n");
}

async function buildEngineBlock() {
  const parts = [];
  for (const f of ORDER) {
    const body = stripFile(await readFile(join(SRC, f), "utf8"));
    parts.push(`  // ───────────────────────────── src/${f} ─────────────────────────────`);
    parts.push(indent(body));
  }
  return [
    "// deno-lint-ignore-file",
    "// Canonical source: kolekto-fe-old/kolekto-shared-financial/src — regenerate with `npm run bundle:edge`.",
    "const FPE = (() => {",
    parts.join("\n"),
    `  return { ${PUBLIC.join(", ")} };`,
    "})();",
  ].join("\n");
}

async function patch(file, block) {
  const text = await readFile(file, "utf8");
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (b === -1 || e === -1 || e < b) {
    throw new Error(`markers not found (or out of order) in ${file}`);
  }
  const before = text.slice(0, b + BEGIN.length);
  const after = text.slice(e);
  const next = `${before}\n${block}\n${after}`;
  await writeFile(file, next);
  console.log(`[bundle:edge] injected engine → ${file}`);
}

const targets = process.argv.slice(2);
if (targets.length === 0) {
  // Default targets relative to the repo (kolekto-fe-old).
  const repo = resolve(pkgRoot, "..");
  targets.push(
    join(repo, "supabase/functions/verify-paystack-payment/_shared1.ts"),
    join(repo, "supabase/functions/initiate-paystack-payment/index.ts")
  );
}

const block = await buildEngineBlock();
for (const t of targets) await patch(t, block);
console.log("[bundle:edge] done.");
